
-- 1. CATALOGOS

-- Empresas que crean los modelos. El pais se guarda una sola vez (3FN).
CREATE TABLE developers (
    developer_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    developer_name    VARCHAR(60) NOT NULL UNIQUE,
    developer_country VARCHAR(2)              -- ISO de 2 letras; NULL si se desconoce
);

-- Proveedores de API que sirven los modelos.
CREATE TABLE providers (
    provider_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_name VARCHAR(60) NOT NULL UNIQUE
);

-- Las 12 capacidades (antes eran las columnas supports_*).
CREATE TABLE capabilities (
    capability_id   INTEGER PRIMARY KEY,
    capability_name VARCHAR(30) NOT NULL UNIQUE
);

-- Los 8 tipos de precio y su unidad.
CREATE TABLE price_types (
    price_type_id   INTEGER PRIMARY KEY,
    price_name      VARCHAR(30) NOT NULL UNIQUE,
    unit_of_measure VARCHAR(20) NOT NULL
);


-- 2. TABLA CENTRAL

CREATE TABLE models (
    model_id           VARCHAR(150) PRIMARY KEY,
    model_name         VARCHAR(150),
    developer_id       INTEGER      NOT NULL,
    provider_id        INTEGER      NOT NULL,
    mode               VARCHAR(30)  NOT NULL,
    in_current_catalog BOOLEAN      NOT NULL,   
    max_input_tokens   INTEGER,
    max_output_tokens  INTEGER,
    deprecation_date   DATE,
    first_listed_week  DATE,
    source_url         TEXT,
    CONSTRAINT fk_models_developer
        FOREIGN KEY (developer_id) REFERENCES developers (developer_id),
    CONSTRAINT fk_models_provider
        FOREIGN KEY (provider_id) REFERENCES providers (provider_id),
    CONSTRAINT chk_models_mode
        CHECK (mode IN ('audio_speech', 'audio_transcription', 'chat', 'completion',
                        'embedding', 'image_edit', 'image_generation', 'moderation',
                        'ocr', 'rerank', 'realtime', 'responses', 'search',
                        'video_generation'))
);



-- 3. RELACIONES Y HECHOS

CREATE TABLE model_capabilities (
    model_id      VARCHAR(150) NOT NULL,
    capability_id INTEGER      NOT NULL,
    PRIMARY KEY (model_id, capability_id),
    CONSTRAINT fk_model_capabilities_model
        FOREIGN KEY (model_id) REFERENCES models (model_id),
    CONSTRAINT fk_model_capabilities_capability
        FOREIGN KEY (capability_id) REFERENCES capabilities (capability_id)
);


CREATE TABLE model_prices (
    model_id      VARCHAR(150)   NOT NULL,
    price_type_id INTEGER        NOT NULL,
    amount_usd    NUMERIC(24,18) NOT NULL,
    PRIMARY KEY (model_id, price_type_id),
    CONSTRAINT fk_model_prices_model
        FOREIGN KEY (model_id) REFERENCES models (model_id),
    CONSTRAINT fk_model_prices_price_type
        FOREIGN KEY (price_type_id) REFERENCES price_types (price_type_id),
    CONSTRAINT chk_model_prices_amount
        CHECK (amount_usd >= 0)
);


CREATE TABLE price_history_weekly (
    model_id                   VARCHAR(150) NOT NULL,
    week_start                 DATE         NOT NULL,   -- lunes de la semana
    input_price_per_1m_tokens  NUMERIC(24,18),
    output_price_per_1m_tokens NUMERIC(24,18),
    max_input_tokens           INTEGER,
    PRIMARY KEY (model_id, week_start),
    CONSTRAINT fk_price_history_model
        FOREIGN KEY (model_id) REFERENCES models (model_id)
);


-- 4. MOVER LAS TABLAS AL TABLESPACE DEL PROYECTO

ALTER TABLE developers           SET TABLESPACE ts_ai_models;
ALTER TABLE providers            SET TABLESPACE ts_ai_models;
ALTER TABLE capabilities         SET TABLESPACE ts_ai_models;
ALTER TABLE price_types          SET TABLESPACE ts_ai_models;
ALTER TABLE models               SET TABLESPACE ts_ai_models;
ALTER TABLE model_capabilities   SET TABLESPACE ts_ai_models;
ALTER TABLE model_prices         SET TABLESPACE ts_ai_models;
ALTER TABLE price_history_weekly SET TABLESPACE ts_ai_models;



-- 5. VERIFICACION: en que tablespace quedo cada tabla
--    Las stg_ deben salir en pg_default y las 8 nuevas en ts_ai_models.

SELECT
    c.relname                                     AS tabla,
    COALESCE(t.spcname, 'pg_default')             AS tablespace,
    PG_SIZE_PRETTY(PG_TOTAL_RELATION_SIZE(c.oid)) AS tamanio
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_tablespace t ON c.reltablespace = t.oid
WHERE c.relkind = 'r'
  AND n.nspname = 'public'
ORDER BY t.spcname NULLS LAST, c.relname;